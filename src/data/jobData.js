export function buildJobSearchUrl(portal, roleTitle, location = "India") {
  const query = encodeURIComponent(roleTitle);
  const loc = encodeURIComponent(location);
  
  switch (portal.toLowerCase()) {
    case 'linkedin':
      return `https://www.linkedin.com/jobs/search/?keywords=${query}&location=${loc}`;
    case 'internshala':
      return `https://internshala.com/fresher-jobs/keywords-${query.toLowerCase().replace(/%20|\s+/g, '-')}/`;
    case 'naukri':
      return `https://www.naukri.com/${query.toLowerCase().replace(/%20|\s+/g, '-')}-jobs-in-${loc.toLowerCase()}`;
    case 'indeed':
      return `https://in.indeed.com/jobs?q=${query}&l=${loc}`;
    case 'wellfound':
      return `https://wellfound.com/jobs?q=${query}`;
    case 'google':
      return `https://www.google.com/about/careers/applications/jobs/results/?q=${query}`;
    default:
      return `https://www.google.com/search?q=${query}+jobs+in+${loc}`;
  }
}
